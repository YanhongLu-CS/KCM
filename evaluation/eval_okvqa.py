import argparse
from ast import literal_eval
from pathlib import Path

import numpy as np
import pandas as pd

import okvqa_evaluation as evaluation


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input-file",
        type=str,
        required=True,
        help="Prediction CSV generated by kcm_okvqa_llava.py",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]

    annotation_file = (
        root
        / "data"
        / "eval_data"
        / "okvqa"
        / "a_ok_vqa_val_fixed_annots.csv"
    )

    val_annotations_df = pd.read_csv(annotation_file)
    val_annotations_df["answers"] = (
        val_annotations_df["answers"].apply(literal_eval)
    )

    results_df = pd.read_csv(args.input_file)

    results_df["llama_answer"] = (
        results_df["llama_answer"]
        .fillna("")
        .astype(str)
    )

    results_df = pd.merge(
        val_annotations_df,
        results_df,
        on="question_id",
    )

    results_df["acc"] = results_df.apply(
        lambda row: evaluation.okvqa_ems(
            row["llama_answer"],
            row["answers"],
            row["question_id"],
        ),
        axis=1,
    )

    print("Annotation samples:", len(val_annotations_df))
    print("Prediction samples:", len(pd.read_csv(args.input_file)))
    print("Evaluated samples:", len(results_df))
    print("VQA acc:", np.round(results_df["acc"].mean(), 3))


if __name__ == "__main__":
    main()
